    events = []
    real_log_event = pnr_openroad.log_event

    def _record(logger, level, event, **fields):
        events.append(event)
        real_log_event(logger, level, event, **fields)

    def _no_space(*_a, **_k):
        raise OSError(28, "No space left on device")

