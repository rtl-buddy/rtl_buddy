_PARAM_STUB = (
    "(* blackbox *)\n"
    "module blk_top #(parameter int W = 8, localparam int AW = $clog2(W)) (\n"
    "  input logic clk, input logic [W-1:0] d, output logic [W-1:0] q);\n"
    "endmodule\n"
    "module glue (input wire a, output wire z);\n"
    "  assign z = ~a;\n"
    "endmodule\n"
)


def test_blackbox_modules_spans_a_parameterised_header():
    [bb] = block_params.blackbox_modules(_PARAM_STUB)
    assert bb.name == "blk_top"
    assert _PARAM_STUB[bb.header_start : bb.header_end].endswith(
        "output logic [W-1:0] q);"
    )
    assert _PARAM_STUB[bb.start : bb.end].endswith("endmodule")


def test_the_openroad_backend_drops_a_parameterised_stub_with_a_master(tmp_path):
    """Stage 2 reads the block's LEF and Liberty; a stub copy of the SV header would fail STA-0171."""
    from test_synth import _make_openroad, _make_synth_cfg, _write_filelist

    src = _write(tmp_path / "blk_bb.sv", _PARAM_STUB)
    or_synth = _make_openroad(
        tmp_path, synth_cfg=_make_synth_cfg(name="test_synth", model_name="top")
    )
    _write_filelist(or_synth, src)

    [stub] = or_synth._write_or_blackbox_stubs({"blk_top"})

    text = Path(stub).read_text()
    assert "blk_top" not in text
    assert "module glue" in text
    # Without a master the header is kept as a port-only stub.
    [stub] = or_synth._write_or_blackbox_stubs(set())
    text = Path(stub).read_text()
    assert (
        "module blk_top #(parameter int W = 8, localparam int AW = $clog2(W))" in text
    )
    assert text.count("endmodule") == 2


def test_the_synth_runner_hands_the_backend_its_resolved_blocks(tmp_path, monkeypatch):
    from unittest.mock import MagicMock

    from rtl_buddy.tools import synth_yosys
    from test_pnr_blocks import _synth_runner

    _block_suite(tmp_path)
    seen = {}

    def _fake_run(self):
        seen["blocks"] = [b.ref.name for b in self.blocks]
        return MagicMock(results={"result": "PASS", "desc": None})

    monkeypatch.setattr(synth_yosys.YosysSynth, "run", _fake_run)
    runner = _synth_runner(
        tmp_path,
        "    blocks:\n      - {name: blk_top, pnr: blk_pnr, pnr-path: ../blk/pnr.yaml}\n",
    )

    runner.run()

    assert seen == {"blocks": ["blk_top"]}
