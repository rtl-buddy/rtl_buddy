def test_an_unconnected_input_fails_and_an_unconnected_output_warns(tmp_path):
    with pytest.raises(BlockParamError, match="input pin 'd' is not connected"):
        _check_ports(tmp_path, "blk_top u_blk (.clk(clk), .d(), .q(q));")
